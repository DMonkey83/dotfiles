#!/usr/bin/env bash
# Copy the configs and package lists of THIS machine into the repo.
# Run it on the PC whose setup you want to save, then review `git diff` and commit.
#
#   scripts/sync.sh             # configs + package lists
#   scripts/sync.sh configs     # configs only
#   scripts/sync.sh packages    # package lists only
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

sync_configs() {
  info "Copying ~/.config entries into config/"
  mkdir -p "$DOTFILES/config" "$DOTFILES/home"
  local item
  for item in "${CONFIG_ITEMS[@]}"; do
    if [[ ! -e $HOME/.config/$item ]]; then
      warn "~/.config/$item does not exist, skipping"
      continue
    fi
    # Start from scratch so files deleted locally disappear from the repo too.
    rm -rf "${DOTFILES:?}/config/$item"
    rsync -a "${RSYNC_EXCLUDES[@]}" "$HOME/.config/$item" "$DOTFILES/config/"
  done

  # JaKooLit scripts create absolute symlinks (e.g. waybar/config); make them
  # relative so they survive a different $HOME.
  local link target
  while IFS= read -r -d '' link; do
    target=$(readlink "$link")
    [[ $target == "$HOME/.config/"* ]] || continue
    ln -sfn "$(realpath -m --relative-to="$(dirname "$link")" "$DOTFILES/config/${target#"$HOME/.config/"}")" "$link"
  done < <(find "$DOTFILES/config" -type l -print0)

  info "Copying home files into home/"
  for item in "${HOME_ITEMS[@]}"; do
    if [[ -e $HOME/$item ]]; then
      rsync -a "$HOME/$item" "$DOTFILES/home/"
    else
      warn "~/$item does not exist, skipping"
    fi
  done
}

sync_packages() {
  info "Writing package lists into packages/"
  local header="# Generated by scripts/sync.sh - overwritten on every sync"

  # Explicitly installed repo packages, minus the hand-maintained system/GPU lists.
  { echo "$header (manual additions go in extra.txt)"
    pacman -Qqen | grep -vxF -f <(read_list "$PKG_DIR/system.txt" "$PKG_DIR/amd.txt") || true
  } > "$PKG_DIR/repo.txt"

  { echo "$header (manual additions go in extra.txt)"; pacman -Qqem; } > "$PKG_DIR/aur.txt"

  if command -v cargo >/dev/null; then
    # One `cargo install` argument set per line: crate name, --git URL or --path DIR.
    { echo "$header"
      cargo install --list | awk '/^[^ ].*:$/ {
        src = $3; gsub(/[():]/, "", src); sub(/#.*/, "", src)
        if (src == "")            print $1
        else if (src ~ /\/\//)    print "--git https://" substr(src, index(src, "//") + 2)
        else                      print "--path " src
      }'
    } > "$PKG_DIR/cargo.txt"
  fi

  if load_nvm; then
    set +u
    local default
    default=$(nvm version default)
    { echo "$header"
      echo "# Node versions (via nvm); the first one becomes the default"
      echo "${default#v}" | cut -d. -f1
      nvm ls --no-colors --no-alias | grep -oE 'v[0-9]+' | tr -d v | sort -un | grep -vx "$(echo "${default#v}" | cut -d. -f1)" || true
    } > "$PKG_DIR/node.txt"
    { echo "$header"
      echo "# Global npm packages for the default Node version"
      nvm exec --silent default npm ls -g --depth=0 --parseable 2>/dev/null \
        | sed -n 's#.*/lib/node_modules/##p' | grep -vxE 'npm|corepack' || true
    } > "$PKG_DIR/npm.txt"
    set -u
  fi
}

case "${1:-all}" in
  all)      sync_configs; sync_packages ;;
  configs)  sync_configs ;;
  packages) sync_packages ;;
  *)        die "usage: $0 [all|configs|packages]" ;;
esac

info "Done. Review with: git -C \"$DOTFILES\" status && git -C \"$DOTFILES\" diff"
